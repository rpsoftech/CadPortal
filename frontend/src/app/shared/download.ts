/** Saves a Blob through a temporary link (used for the PDF and CSV exports). */
export function saveBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 10_000);
}

/**
 * Starts a browser download of a URL that needs no sign-in header (a signed link), so the browser itself
 * streams the file to disk. Nothing is held in the page, which matters for a ZIP of hundreds of megabytes.
 */
export function startDownload(url: string, filename: string): void {
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.rel = 'noopener';
  document.body.appendChild(a);
  a.click();
  a.remove();
}
